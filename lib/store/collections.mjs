// Where a store keeps its records: the queue's entries, saved feeds, drafts,
// pending removals, settings. Every store is built on one of these, with the
// same five methods, so the same store code runs on your Mac (JSON files) and
// hosted (Postgres).
//
// - JsonListCollection: an ordered list inside one JSON file. These are the
//   files the app has always written (out/outbox.json, feeds.json,
//   out/removals.json, config.json), unchanged on disk.
// - JsonDirCollection: one JSON file per record (drafts/<id>.json).
// - PgCollection: rows of the `records` table for one owner and one kind.
//
// Records are plain JSON objects. Order is the order they were first added.

import fs from 'node:fs/promises';
import path from 'node:path';

/**
 * Run writes to one file one at a time, so two requests that each read,
 * change and write the same index cannot lose one another's change.
 */
const queues = new Map();
function serialize(file, task) {
  const previous = queues.get(file) || Promise.resolve();
  const next = previous.then(task, task);
  queues.set(
    file,
    next.catch(() => {}).finally(() => {
      if (queues.get(file) === next) queues.delete(file);
    })
  );
  return next;
}

async function writeJson(file, value) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.tmp`;
  await fs.writeFile(temp, `${JSON.stringify(value, null, 2)}\n`);
  await fs.rename(temp, file);
}

export class JsonListCollection {
  /**
   * @param {string} file     The JSON file.
   * @param {string} listKey  The property holding the list ("items", "feeds").
   * @param {(r: object) => string} [idOf] How a record is identified.
   */
  constructor(file, listKey, idOf = (r) => r.id) {
    this.file = file;
    this.listKey = listKey;
    this.idOf = idOf;
  }

  async #read() {
    try {
      const raw = JSON.parse(await fs.readFile(this.file, 'utf8'));
      return Array.isArray(raw?.[this.listKey]) ? raw[this.listKey] : [];
    } catch {
      return [];
    }
  }

  #write(records) {
    return writeJson(this.file, { [this.listKey]: records });
  }

  async all() {
    return this.#read();
  }

  async get(id) {
    return (await this.#read()).find((r) => this.idOf(r) === id) || null;
  }

  /** Insert, or replace the record with the same id where it stands. */
  put(record) {
    return serialize(this.file, async () => {
      const records = await this.#read();
      const id = this.idOf(record);
      const index = records.findIndex((r) => this.idOf(r) === id);
      if (index === -1) records.push(record);
      else records[index] = record;
      await this.#write(records);
      return record;
    });
  }

  /** Change a record under the write lock: `change(current)` returns the new one. */
  update(id, change) {
    return serialize(this.file, async () => {
      const records = await this.#read();
      const index = records.findIndex((r) => this.idOf(r) === id);
      if (index === -1) return null;
      records[index] = change(records[index]);
      await this.#write(records);
      return records[index];
    });
  }

  delete(id) {
    return serialize(this.file, async () => {
      const records = await this.#read();
      const left = records.filter((r) => this.idOf(r) !== id);
      if (left.length === records.length) return false;
      await this.#write(left);
      return true;
    });
  }

  /** Drop several records in one write. */
  deleteMany(ids) {
    const drop = new Set(ids);
    return serialize(this.file, async () => {
      const records = await this.#read();
      const left = records.filter((r) => !drop.has(this.idOf(r)));
      if (left.length !== records.length) await this.#write(left);
      return records.length - left.length;
    });
  }
}

export class JsonDirCollection {
  /**
   * @param {string} dir A folder of <id>.json files.
   * @param {RegExp} [idPattern] Ids accepted; anything else is refused.
   */
  constructor(dir, idPattern = /^[0-9a-f-]{36}$/i) {
    this.dir = dir;
    this.idPattern = idPattern;
  }

  #pathFor(id) {
    // Ids are generated by the app, but never trust one off the wire.
    if (!this.idPattern.test(String(id || ''))) throw new Error('Invalid id.');
    return path.join(this.dir, `${id}.json`);
  }

  async all() {
    await fs.mkdir(this.dir, { recursive: true });
    const records = [];
    for (const name of await fs.readdir(this.dir)) {
      if (!name.endsWith('.json')) continue;
      try {
        records.push(JSON.parse(await fs.readFile(path.join(this.dir, name), 'utf8')));
      } catch {
        /* skip an unreadable or half-written file rather than failing the list */
      }
    }
    return records;
  }

  async get(id) {
    try {
      return JSON.parse(await fs.readFile(this.#pathFor(id), 'utf8'));
    } catch (err) {
      if (err.code === 'ENOENT') return null;
      throw err;
    }
  }

  put(record) {
    const file = this.#pathFor(record.id);
    // Write to a temp file and rename, so a save interrupted mid-write cannot
    // truncate the previous version.
    return serialize(file, async () => {
      await writeJson(file, record);
      return record;
    });
  }

  update(id, change) {
    const file = this.#pathFor(id);
    return serialize(file, async () => {
      const current = await this.get(id);
      if (!current) return null;
      const next = change(current);
      await writeJson(file, next);
      return next;
    });
  }

  async delete(id) {
    try {
      await fs.unlink(this.#pathFor(id));
      return true;
    } catch (err) {
      if (err.code === 'ENOENT') return false;
      throw err;
    }
  }

  async deleteMany(ids) {
    let n = 0;
    for (const id of ids) if (await this.delete(id)) n++;
    return n;
  }
}

export class PgCollection {
  /**
   * @param {{query: Function}} db
   * @param {string} owner  Whose records these are.
   * @param {string} kind   Which store ("outbox", "feeds", …).
   * @param {(r: object) => string} [idOf]
   */
  constructor(db, owner, kind, idOf = (r) => r.id) {
    this.db = db;
    this.owner = owner;
    this.kind = kind;
    this.idOf = idOf;
  }

  async all() {
    const { rows } = await this.db.query(
      'SELECT data FROM records WHERE owner = $1 AND kind = $2 ORDER BY seq',
      [this.owner, this.kind]
    );
    return rows.map((r) => r.data);
  }

  async get(id) {
    const { rows } = await this.db.query(
      'SELECT data FROM records WHERE owner = $1 AND kind = $2 AND id = $3',
      [this.owner, this.kind, String(id)]
    );
    return rows[0]?.data || null;
  }

  async put(record) {
    await this.db.query(
      `INSERT INTO records (owner, kind, id, data) VALUES ($1, $2, $3, $4)
       ON CONFLICT (owner, kind, id) DO UPDATE SET data = EXCLUDED.data, updated_at = now()`,
      [this.owner, this.kind, String(this.idOf(record)), JSON.stringify(record)]
    );
    return record;
  }

  /** Read, change and write one record inside a transaction with a row lock. */
  async update(id, change) {
    return this.db.transaction(async (tx) => {
      const { rows } = await tx.query(
        'SELECT data FROM records WHERE owner = $1 AND kind = $2 AND id = $3 FOR UPDATE',
        [this.owner, this.kind, String(id)]
      );
      if (!rows[0]) return null;
      const next = change(rows[0].data);
      await tx.query(
        'UPDATE records SET data = $4, updated_at = now() WHERE owner = $1 AND kind = $2 AND id = $3',
        [this.owner, this.kind, String(id), JSON.stringify(next)]
      );
      return next;
    });
  }

  async delete(id) {
    const { rows } = await this.db.query(
      'DELETE FROM records WHERE owner = $1 AND kind = $2 AND id = $3 RETURNING id',
      [this.owner, this.kind, String(id)]
    );
    return rows.length > 0;
  }

  async deleteMany(ids) {
    if (!ids.length) return 0;
    const { rows } = await this.db.query(
      'DELETE FROM records WHERE owner = $1 AND kind = $2 AND id = ANY($3::text[]) RETURNING id',
      [this.owner, this.kind, ids.map(String)]
    );
    return rows.length;
  }
}
