// File-backed draft store for the built-in editor.
//
// One JSON file per draft under drafts/, so work survives a server restart and
// stays readable/greppable on disk. Drafts are independent of converted EPUBs:
// you can edit a draft repeatedly and convert it whenever you like.

import { randomUUID } from 'node:crypto';

import { JsonDirCollection } from './store/collections.mjs';

const MAX_HTML_BYTES = 4 * 1024 * 1024;

export class DraftStore {
  /** @param {string | object} source A folder of <id>.json files, or a collection. */
  constructor(source) {
    this.records = typeof source === 'string' ? new JsonDirCollection(source) : source;
  }

  #checkId(id) {
    // Ids are generated by this class, but never trust one off the wire.
    if (!/^[0-9a-f-]{36}$/i.test(String(id || ''))) throw new Error('Invalid draft id.');
    return String(id);
  }

  async list() {
    const drafts = (await this.records.all()).map(summarize);
    // Most recently edited first — that's the one you want to reopen.
    return drafts.sort((a, b) => String(b.updatedAt).localeCompare(String(a.updatedAt)));
  }

  async get(id) {
    return this.records.get(this.#checkId(id));
  }

  /** Create when `id` is absent, otherwise update in place. */
  async save({ id, title, author, markdown }) {
    const body = String(markdown ?? '');
    if (Buffer.byteLength(body) > MAX_HTML_BYTES) throw new Error('Draft is too large to save.');

    const now = new Date().toISOString();
    let draft;

    if (id) {
      const existing = await this.get(id);
      if (!existing) throw new Error('That draft no longer exists.');
      draft = { ...existing, updatedAt: now };
    } else {
      draft = { id: randomUUID(), createdAt: now, updatedAt: now };
    }

    draft.title = String(title ?? '').slice(0, 300);
    draft.author = String(author ?? '').slice(0, 200);
    draft.markdown = body;
    // Drop the pre-markdown field once a draft has been re-saved.
    delete draft.html;

    await this.records.put(draft);
    return draft;
  }

  async remove(id) {
    return this.records.delete(this.#checkId(id));
  }
}

function summarize(draft) {
  const source =
    typeof draft.markdown === 'string'
      ? draft.markdown.replace(/[#>*_`~]/g, ' ')
      : String(draft.html || '').replace(/<[^>]*>/g, ' ');
  const text = source.replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

  return {
    id: draft.id,
    title: draft.title || '',
    author: draft.author || '',
    createdAt: draft.createdAt,
    updatedAt: draft.updatedAt,
    chars: text.length,
    words: text ? text.split(/\s+/).length : 0,
  };
}

export { summarize };
